// 1. 파싱 (빈 칸 → 0)
function toNum(s) {
  const v = String(s).replace(/,/g, "").trim();
  return v === "" ? 0 : Number(v);
}

const stores = raw.split("\n").map((line) => {
  const parts = line.split("\t");
  const code = parts[0];
  const name = parts[1];
  const total = toNum(parts[2]);
  const cats = {};
  CATEGORIES.forEach((c, i) => {
    cats[c] = toNum(parts[3 + i]);
  });
  // 비중 (점포 합계 대비)
  const ratios = {};
  Object.entries(cats).forEach(([c, v]) => {
    ratios[c] = total > 0 ? Math.round((v / total) * 1000) / 10 : 0;
  });
  // 강세 카테고리 (15% 이상, 최대 4개, 비중 내림차순)
  const strong = Object.entries(ratios)
    .filter(([, r]) => r >= STRONG_THRESHOLD_PCT)
    .sort((a, b) => b[1] - a[1])
    .slice(0, MAX_STRONG)
    .map(([c]) => c);
  return { storeCode: code, storeName: name, total, categories: cats, ratios, strongCategories: strong };
});

// 2. 41점 마스터 매칭
const homeplusContent = readFileSync("src/data/homeplus.ts", "utf-8");
const match = homeplusContent.match(/export const ELAND_STORES[^=]*=\s*(\[[\s\S]*?\n\]);/);
const elandStores = eval(match[1]);
function normalize(s) {
  return s.replace(/^NC/, "").replace(/점$/, "").replace(/\s+/g, "");
}
const nameToId = new Map();
elandStores.forEach((s) => nameToId.set(normalize(s.name), s.id));

const allEnriched = stores.map((st) => ({
  storeId: nameToId.get(normalize(st.storeName)) ?? null,
  ...st,
}));
const enriched = allEnriched.filter((s) => s.storeId !== null);
const excluded = allEnriched.filter((s) => s.storeId === null);

console.log(`41점 마스터 매칭: ${enriched.length} / 41`);
if (excluded.length > 0) {
  console.log(`제외된 ${excluded.length}개점:`);
  excluded.forEach((s) => console.log(`  ${s.storeCode} ${s.storeName} (총 ${Math.round(s.total / 1e8)}억)`));
}

// 3. JSON 저장
const out = {
  $schema: "./store-categories.schema.json",
  version: "1.0",
  compiledAt: new Date().toISOString().slice(0, 10),
  period: PERIOD,
  source: "ERP 4월 한달 점포별 × 10개 카테고리 매출",
  categories: CATEGORIES,
  strongRule: `점포 합계의 ${STRONG_THRESHOLD_PCT}% 이상, 최대 ${MAX_STRONG}개`,
  grandTotal: {
    revenueWon: enriched.reduce((s, x) => s + x.total, 0),
    byCategory: Object.fromEntries(
      CATEGORIES.map((c) => [c, enriched.reduce((s, x) => s + x.categories[c], 0)])
    ),
  },
  stores: enriched,
};
writeFileSync("src/data/store-categories.json", JSON.stringify(out, null, 2));
console.log(`✅ src/data/store-categories.json 저장`);
console.log(`   총 매출: ${Math.round(out.grandTotal.revenueWon / 1e8).toLocaleString()}억`);

// 4. eland-meta.ts tenant_mix.categories 자동 채움
const idToStrong = new Map();
enriched.forEach((s) => idToStrong.set(s.storeId, s.strongCategories));

let metaContent = readFileSync("src/data/eland-meta.ts", "utf-8");
for (let id = 1; id <= 41; id++) {
  const cats = idToStrong.get(id);
  if (!cats || cats.length === 0) continue;
  const regex = new RegExp(`(store_id: ${id},[\\s\\S]*?categories: )\\[\\]`, "g");
  metaContent = metaContent.replace(regex, `$1${JSON.stringify(cats)}`);
}
writeFileSync("src/data/eland-meta.ts", metaContent);
console.log("✅ src/data/eland-meta.ts tenant_mix.categories 자동 채움 완료");

// 5. 카테고리 빈도 분포
const catFreq = {};
CATEGORIES.forEach((c) => (catFreq[c] = 0));
enriched.forEach((s) => s.strongCategories.forEach((c) => catFreq[c]++));
console.log("\n📊 강세 카테고리 빈도 (몇 개점에서 Top4 안에 들었는지):");
Object.entries(catFreq)
  .sort((a, b) => b[1] - a[1])
  .forEach(([c, n]) => console.log(`   ${c}: ${n}개점`));

// 6. 흥미로운 점포 — 특화 매장 (단일 카테고리 30%+ 비중)
console.log("\n🎯 특화 매장 (단일 카테고리 30%+ 비중):");
enriched.forEach((s) => {
  const top = Object.entries(s.ratios).sort((a, b) => b[1] - a[1])[0];
  if (top[1] >= 30) {
    console.log(`   ${s.storeName}: ${top[0]} ${top[1]}% (총 ${Math.round(s.total / 1e8)}억)`);
  }
});
