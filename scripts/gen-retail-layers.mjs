// 리테일 지도 레이어별 점포 수 자동 집계 → src/data/retail-layer-counts.ts 재생성
//
// 왜 필요한가: 사이드바 '리테일 지도' 하위 라벨의 "…N점" 숫자가 예전엔 손으로
// 박혀 있어(예: "다이소 1,714점") 데이터가 갱신되면 라벨이 거짓말을 했다.
// 이 스크립트는 각 체인 데이터 파일(src/data/<chain>.ts)의 실제 레코드 수를 세어
// 가벼운 숫자 맵으로 떨어뜨린다. 사이드바는 좌표 데이터를 번들에 넣지 않고
// 이 숫자 맵만 읽어 라벨을 렌더한다.
//
// 사용: 체인 데이터 파일을 갱신한 뒤 `node scripts/gen-retail-layers.mjs` 실행 후 커밋.
// (src/data/retail-layers.test.ts 가 재생성 누락을 CI에서 잡아준다.)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_DIR = join(__dirname, "..", "src", "data");
const OUT_FILE = join(DATA_DIR, "retail-layer-counts.ts");

// layer key → 데이터 파일명(확장자 제외). 대부분 동일하나 8seconds→eightseconds 예외.
// 레이어 목록/순서/색상 등 메타데이터는 src/data/retail-layers.ts 가 소유한다.
const LAYER_FILES = {
  lotte: "lotte",
  hyundai: "hyundai",
  shinsegae: "shinsegae",
  ak: "ak",
  galleria: "galleria",
  artbox: "artbox",
  abcmart: "abcmart",
  "8seconds": "eightseconds",
  spao: "spao",
  mixxo: "mixxo",
  daiso: "daiso",
  oliveyoung: "oliveyoung",
  modernhouse: "modernhouse",
  muji: "muji",
  hanssem: "hanssem",
  livart: "livart",
  iloom: "iloom",
  nitori: "nitori",
  uniqlo: "uniqlo",
  entersix: "entersix",
  moda: "moda",
  savezone: "savezone",
  lf: "lf",
  emart: "emart",
  lottemart: "lottemart",
  hanaromart: "hanaromart",
};

// 각 체인 파일은 ChainStore[] 하나만 담고, 레코드마다 정확히 하나의 "lat" 키를 가진다.
// → `"lat":` 출현 수 = 점포 수. (인터페이스 선언은 따옴표 없는 `lat:` 라 걸리지 않고,
//  한글 주소에 `"lat":` 이 들어갈 일도 없다.)
function countStores(file) {
  const text = readFileSync(join(DATA_DIR, `${file}.ts`), "utf8");
  const matches = text.match(/"lat"\s*:/g);
  return matches ? matches.length : 0;
}

const counts = {};
for (const [layer, file] of Object.entries(LAYER_FILES)) {
  const n = countStores(file);
  if (n === 0) {
    console.error(`⚠️  ${layer} (${file}.ts): 점포 0개 — 파일 형식이 바뀌었는지 확인하세요.`);
  }
  counts[layer] = n;
}

const body = Object.entries(counts)
  .map(([layer, n]) => `  ${/^[a-z]/i.test(layer) ? layer : JSON.stringify(layer)}: ${n},`)
  .join("\n");

const out = `// AUTO-GENERATED by scripts/gen-retail-layers.mjs — 직접 수정하지 마세요.
// 체인 데이터 갱신 후 \`node scripts/gen-retail-layers.mjs\` 로 재생성.
// 레이어 메타데이터(색상·그룹·순서)는 ./retail-layers.ts 참고.

export const RETAIL_LAYER_COUNTS: Record<string, number> = {
${body}
};
`;

writeFileSync(OUT_FILE, out, "utf8");
const total = Object.values(counts).reduce((a, b) => a + b, 0);
console.log(`✅ ${OUT_FILE} 갱신 — ${Object.keys(counts).length}개 레이어, 총 ${total.toLocaleString()}점`);
